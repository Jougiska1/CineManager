    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
         Filme filme = new Filme();
        filme.setTitulo(txtTitulo.getText());
        filme.setGenero(txtGenero.getText());
        filme.setAnoLancamento(Integer.parseInt(txtAno.getText()));
        filme.setValorLocacao(Double.parseDouble(txtValor.getText()));
        filme.setQuantidadeEstoque(Integer.parseInt(txtEstoque.getText()));

        FilmeDAO dao = new FilmeDAO();
        dao.cadastrarFilme(filme);

        txtTitulo.setText("");
        txtGenero.setText("");
        txtAno.setText("");
        txtValor.setText("");
        txtEstoque.setText("");
    }//GEN-LAST:event_btnSalvarActionPerformed

