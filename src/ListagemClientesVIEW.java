        private void carregarClientes() {
        ClienteDAO dao = new ClienteDAO();
        java.util.ArrayList<Cliente> lista = dao.listarClientes();
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabelaClientes.getModel();
        model.setNumRows(0);
        for (Cliente c : lista) {
            model.addRow(new Object[]{c.getIdCliente(), c.getNome(), c.getCpf(), c.getEmail()});
        }
    }
