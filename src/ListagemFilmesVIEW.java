        private void carregarFilmes() {
        FilmeDAO dao = new FilmeDAO();
        java.util.ArrayList<Filme> lista = dao.listarFilmes();
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabelaFilmes.getModel();
        model.setNumRows(0);
        for (Filme f : lista) {
            model.addRow(new Object[]{f.getIdFilme(), f.getTitulo(), f.getGenero(), f.getAnoLancamento(), f.getValorLocacao(), f.getQuantidadeEstoque()});
        }
    }
